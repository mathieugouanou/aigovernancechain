// Agent oversight policy packs: compile the agent section of AI_GOVERNANCE.md to OPA Rego and Cedar.
// The compiled policies mirror rails/rails.mjs, so the runtime rails, OPA and Cedar give the same
// allow or block decision for the same request. tests/policy.test.mjs checks this case by case.
//
// Request shape (OPA input, or Cedar context built by your enforcement point):
//   tool                 tool name the agent wants to call
//   amount               money amount of the call, if any (whole currency units for Cedar)
//   recipient_domain     domain of the recipient, if the call sends something
//   instruction_source   who asked for this action: user, email, web, tool_output ...
//   identity             the identity (service account, token owner) the call runs as
//   human_approved       true when a person approved this call
//   approvals            number of people who approved (two-person rule needs 2)
//   calls_before         calls of this tool earlier in the session
//   spent                money already spent this period
//   kill_switch_engaged  true once someone pressed stop
//   consecutive_errors   failed calls in a row (circuit breaker)
//   sql_writes           true when the query changes data (computed by the enforcement point)
//   sql_tables           tables the query touches (computed by the enforcement point)
//   memory_source        for the pseudo-tool "memory.write": where the note came from
import { parseGovernanceMd } from './governance-md.mjs';

export const BOUNDED_SCOPES = ['write', 'payment', 'delete', 'admin', 'execute', 'send'];
export const MEMORY_TOOL = 'memory.write';

export function agentModel(fm) {
  const agent = fm?.agent || {};
  const tools = (agent.tools || []).map(t => ({
    name: String(t.name),
    scope: String(t.scope || 'read'),
    approval: t.approval || 'none',
    run_as: t.run_as ? String(t.run_as) : null,
    limits: t.limits && typeof t.limits === 'object' ? t.limits : null,
  }));
  return {
    system: fm?.system?.name || 'AI system',
    defaultDeny: agent.default_deny !== false,
    tools,
    untrusted: (agent.trust_boundaries || []).filter(b => b.treat_as === 'data').map(b => String(b.source)),
    spend: agent.spend_limit && typeof agent.spend_limit.amount === 'number' ? agent.spend_limit : null,
    breaker: agent.circuit_breaker && Number.isInteger(agent.circuit_breaker.max_consecutive_errors) ? agent.circuit_breaker.max_consecutive_errors : null,
    memory: agent.memory && Array.isArray(agent.memory.write_sources) ? agent.memory.write_sources.map(String) : null,
  };
}

const slug = s => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'agent';
const q = s => JSON.stringify(String(s));
const needsApproval = t => t.approval === 'human' || t.approval === 'two-person';
const approvalsNeeded = t => (t.approval === 'two-person' ? 2 : 1);

function header(fm, lang) {
  const c = lang === 'rego' ? '#' : '//';
  return [
    `${c} Generated by aigovchain policy from AI_GOVERNANCE.md. Do not edit by hand: change the file and compile again.`,
    `${c} System: ${fm?.system?.name || 'AI system'}. Spec: ${fm?.spec || 'ai-governance/v0.1'}.`,
    `${c} These rules translate what the file declares. They do not prove the running agent calls the policy:`,
    `${c} test that every tool call passes through your policy engine. Governance guidance, not legal advice.`,
  ].join('\n');
}

// ---------- OPA Rego (v1 syntax; "import rego.v1" also lets OPA 0.59+ read it) ----------
export function toRego(fm, { pkg = 'aigovernancechain.agent' } = {}) {
  const m = agentModel(fm);
  const tools = Object.fromEntries(m.tools.map(t => [t.name, { scope: t.scope, approval: t.approval, run_as: t.run_as, has_limits: !!t.limits, limits: t.limits || {} }]));
  const L = [];
  L.push(header(fm, 'rego'), '', `package ${pkg}`, '', 'import rego.v1', '');
  L.push(`default_deny := ${m.defaultDeny}`);
  L.push(`tools := ${JSON.stringify(tools, null, 2)}`);
  L.push(`untrusted_sources := ${JSON.stringify(m.untrusted)}`);
  L.push(`spend_limit := ${m.spend ? m.spend.amount : 'null'}`);
  L.push(`circuit_breaker := ${m.breaker ?? 'null'}`);
  L.push(`memory_write_sources := ${m.memory ? JSON.stringify(m.memory) : 'null'}`);
  L.push(`bounded_scopes := ${JSON.stringify(BOUNDED_SCOPES)}`);
  L.push('');
  L.push('default allow := false', '', 'allow if count(deny) == 0', '');
  L.push('decision := {"allow": allow, "requires_human": requires_human, "reasons": deny}', '');
  L.push('tool := tools[input.tool]', '');
  L.push('# The memory pseudo-tool is governed by agent.memory, not by the tools list.');
  L.push(`is_memory if input.tool == ${q(MEMORY_TOOL)}`, '');
  L.push('deny contains "kill switch engaged" if input.kill_switch_engaged == true', '');
  L.push('deny contains "circuit breaker open: too many failed calls in a row" if {');
  L.push('  circuit_breaker != null', '  object.get(input, "consecutive_errors", 0) >= circuit_breaker', '}', '');
  L.push('deny contains msg if {', '  is_memory', '  memory_write_sources != null', '  not input.memory_source in memory_write_sources');
  L.push('  msg := sprintf("memory write from %v is not allowed by agent.memory.write_sources", [object.get(input, "memory_source", "unknown")])', '}', '');
  L.push('deny contains "tool not declared in AI_GOVERNANCE.md (default deny)" if {', '  not is_memory', '  not tools[input.tool]', '  default_deny', '}', '');
  L.push('deny contains msg if {', '  not is_memory', '  tool', '  input.instruction_source in untrusted_sources');
  L.push('  msg := sprintf("action was requested by content from %v, which this system treats as data, not instructions", [input.instruction_source])', '}', '');
  L.push('lim(k) := object.get(tool.limits, k, null)', '');
  L.push('deny contains msg if {', '  tool.run_as != null', '  object.get(input, "identity", null) != tool.run_as');
  L.push('  msg := sprintf("call runs as %v, but this tool may only run as %v", [object.get(input, "identity", "an unknown identity"), tool.run_as])', '}', '');
  L.push('deny contains msg if {', '  max := lim("max_calls")', '  is_number(max)', '  object.get(input, "calls_before", 0) + 1 > max');
  L.push('  msg := sprintf("more than %v calls this session", [max])', '}', '');
  L.push('deny contains msg if {', '  doms := lim("allowed_recipient_domains")', '  is_array(doms)', '  is_string(input.recipient_domain)', '  not lower(input.recipient_domain) in {lower(d) | some d in doms}');
  L.push('  msg := sprintf("recipient domain %v is not in allowed_recipient_domains", [input.recipient_domain])', '}', '');
  L.push('deny contains "query changes data, but the tool is read_only" if {', '  lim("read_only") == true', '  input.sql_writes == true', '}', '');
  L.push('deny contains msg if {', '  tabs := lim("allowed_tables")', '  is_array(tabs)', '  some table in object.get(input, "sql_tables", [])', '  not lower(table) in {lower(t) | some t in tabs}');
  L.push('  msg := sprintf("table %v is not in allowed_tables", [table])', '}', '');
  L.push('over_limit if {', '  is_number(input.amount)', '  is_number(lim("max_amount"))', '  input.amount > lim("max_amount")', '}', '');
  L.push('needs_approval if tool.approval in {"human", "two-person"}', '');
  L.push('requires_human if {', '  needs_approval', '  over_limit', '}', '');
  L.push('requires_human if {', '  needs_approval', '  not is_number(lim("max_amount"))', '}', '');
  L.push('approvals_needed := 2 if tool.approval == "two-person"', 'else := 1', '');
  L.push('human_ok if {', '  input.human_approved == true', '  object.get(input, "approvals", 1) >= approvals_needed', '}', '');
  L.push('deny contains msg if {', '  over_limit', '  not needs_approval');
  L.push('  msg := sprintf("amount %v exceeds max_amount %v", [input.amount, lim("max_amount")])', '}', '');
  L.push('deny contains "human approval required and not given" if {', '  requires_human', '  not human_ok', '}', '');
  L.push('deny contains msg if {', '  spend_limit != null', '  tool', '  is_number(input.amount)', '  object.get(input, "spent", 0) + input.amount > spend_limit');
  L.push('  msg := sprintf("spend limit %v would be exceeded", [spend_limit])', '}', '');
  L.push('deny contains msg if {', '  tool.scope in bounded_scopes', '  not tool.has_limits', '  not needs_approval');
  L.push('  msg := sprintf("%v tool has no limits or approval declared", [tool.scope])', '}');
  return L.join('\n') + '\n';
}

// ---------- Cedar (policies + schema). Amounts are Long: use whole currency units. ----------
export function toCedar(fm) {
  const m = agentModel(fm);
  const agentId = slug(m.system);
  const P = [header(fm, 'cedar'), '', '// Cedar denies anything no policy permits, which matches default_deny: true.', ''];
  const cond = [];
  for (const t of m.tools) {
    const c = [];
    if (t.limits && typeof t.limits.max_amount === 'number') {
      const max = Math.floor(t.limits.max_amount);
      if (needsApproval(t)) c.push(`(if context has amount then (context.amount <= ${max} || (context.human_approved && context.approvals >= ${approvalsNeeded(t)})) else true)`);
      else c.push(`(if context has amount then context.amount <= ${max} else true)`);
    } else if (needsApproval(t)) c.push(`(context.human_approved && context.approvals >= ${approvalsNeeded(t)})`);
    if (BOUNDED_SCOPES.includes(t.scope) && !t.limits && !needsApproval(t)) {
      P.push(`// ${t.name}: ${t.scope} tool with no limits or approval declared, so it is never permitted.`, '');
      continue;
    }
    P.push(`@id(${q('permit-' + t.name)})`);
    P.push(`permit (principal == Agent::${q(agentId)}, action == Action::${q(t.name)}, resource)` + (c.length ? `\nwhen { ${c.join(' && ')} };` : ';'));
    P.push('');
    if (t.run_as) P.push(`@id(${q('identity-' + t.name)})`, `forbid (principal, action == Action::${q(t.name)}, resource)`, `when { if context has identity then context.identity != ${q(t.run_as)} else true };`, '');
    if (t.limits && Number.isInteger(t.limits.max_calls)) P.push(`@id(${q('max-calls-' + t.name)})`, `forbid (principal, action == Action::${q(t.name)}, resource)`, `when { context.calls_before + 1 > ${t.limits.max_calls} };`, '');
    if (t.limits && Array.isArray(t.limits.allowed_recipient_domains)) {
      const doms = t.limits.allowed_recipient_domains.map(d => q(String(d).toLowerCase())).join(', ');
      P.push(`@id(${q('recipients-' + t.name)})`, `forbid (principal, action == Action::${q(t.name)}, resource)`, `when { context has recipient_domain }`, `unless { [${doms}].contains(context.recipient_domain) };`, '');
    }
    if (t.limits && t.limits.read_only === true) P.push(`@id(${q('read-only-' + t.name)})`, `forbid (principal, action == Action::${q(t.name)}, resource)`, `when { context has sql_writes && context.sql_writes };`, '');
    if (t.limits && Array.isArray(t.limits.allowed_tables)) {
      const tabs = t.limits.allowed_tables.map(x => q(String(x).toLowerCase())).join(', ');
      P.push(`@id(${q('tables-' + t.name)})`, `forbid (principal, action == Action::${q(t.name)}, resource)`, `when { context has sql_tables }`, `unless { [${tabs}].containsAll(context.sql_tables) };`, '');
    }
  }
  if (m.memory) {
    P.push(`@id("memory-write")`, `permit (principal == Agent::${q(agentId)}, action == Action::${q(MEMORY_TOOL)}, resource)`, `when { context has memory_source && [${m.memory.map(q).join(', ')}].contains(context.memory_source) };`, '');
  } else {
    P.push(`@id("memory-write")`, `permit (principal == Agent::${q(agentId)}, action == Action::${q(MEMORY_TOOL)}, resource);`, '');
  }
  P.push('@id("kill-switch")', 'forbid (principal, action, resource)', 'when { context.kill_switch_engaged };', '');
  if (m.untrusted.length) P.push('@id("trust-boundary")', `forbid (principal, action, resource)`, `when { action != Action::${q(MEMORY_TOOL)} && context has instruction_source && [${m.untrusted.map(q).join(', ')}].contains(context.instruction_source) };`, '');
  if (m.spend) P.push('@id("spend-limit")', 'forbid (principal, action, resource)', `when { action != Action::${q(MEMORY_TOOL)} && context has amount && context.spent + context.amount > ${Math.floor(m.spend.amount)} };`, '');
  if (m.breaker !== null) P.push('@id("circuit-breaker")', 'forbid (principal, action, resource)', `when { context.consecutive_errors >= ${m.breaker} };`, '');

  const actions = [...m.tools.map(t => t.name), MEMORY_TOOL];
  const S = [
    '// Cedar schema for the policies above. Optional attributes may be left out of the context.',
    'entity Agent;',
    'entity Tool;',
    'type Ctx = {',
    '  kill_switch_engaged: Bool,',
    '  human_approved: Bool,',
    '  approvals: Long,',
    '  calls_before: Long,',
    '  spent: Long,',
    '  consecutive_errors: Long,',
    '  amount?: Long,',
    '  recipient_domain?: String,',
    '  instruction_source?: String,',
    '  identity?: String,',
    '  sql_writes?: Bool,',
    '  sql_tables?: Set<String>,',
    '  memory_source?: String,',
    '};',
    ...actions.map(a => `action ${q(a)} appliesTo { principal: [Agent], resource: [Tool], context: Ctx };`),
  ];
  return { policies: P.join('\n'), schema: S.join('\n') + '\n', principal: `Agent::"${agentId}"` };
}

// Helpers an enforcement point can use to fill sql_writes and sql_tables.
export function sqlFacts(query = '') {
  const s = String(query);
  const writes = /\b(insert|update|delete|drop|alter|truncate|create|grant|revoke|merge|replace)\b/i.test(s);
  const tables = [...s.matchAll(/\b(?:from|join|into|update|table)\s+([A-Za-z_][A-Za-z0-9_.]*)/gi)].map(x => x[1].toLowerCase());
  return { sql_writes: writes, sql_tables: [...new Set(tables)] };
}

export function compilePolicy(src, target = 'rego') {
  const p = typeof src === 'string' ? parseGovernanceMd(src) : { frontMatter: src };
  if (p.error) throw new Error(`Cannot read AI_GOVERNANCE.md: ${p.error}`);
  if (!p.frontMatter.agent) throw new Error('AI_GOVERNANCE.md has no agent section, so there are no agent rules to compile.');
  if (target === 'rego' || target === 'opa') return { 'policy.rego': toRego(p.frontMatter) };
  if (target === 'cedar') { const c = toCedar(p.frontMatter); return { 'policy.cedar': c.policies, 'policy.cedarschema': c.schema }; }
  throw new Error(`Unknown target "${target}". Use rego or cedar.`);
}
