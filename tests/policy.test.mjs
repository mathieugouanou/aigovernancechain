import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { compilePolicy, sqlFacts, agentModel } from '../lib/policy.mjs';
import { parseGovernanceMd } from '../lib/governance-md.mjs';
import { POLICY_TEST_RULES, runEquivalence, loadCedar } from '../scripts/policy-equivalence.mjs';

test('compiles the agent section to OPA Rego', () => {
  const out = compilePolicy(POLICY_TEST_RULES, 'rego');
  const rego = out['policy.rego'];
  assert.match(rego, /^# Generated by aigovchain policy from AI_GOVERNANCE\.md/);
  assert.match(rego, /package aigovernancechain\.agent/);
  assert.match(rego, /default allow := false/);
  for (const tool of ['issue_refund', 'wire_funds', 'run_sql', 'reset_password']) assert.ok(rego.includes(`"${tool}"`), tool);
});

test('compiles the agent section to Cedar policies and schema', () => {
  const out = compilePolicy(POLICY_TEST_RULES, 'cedar');
  assert.ok(out['policy.cedar'].includes('permit'));
  assert.ok(out['policy.cedar'].includes('forbid'));
  assert.ok(out['policy.cedarschema'].includes('action'));
});

test('a file without an agent section has nothing to compile', () => {
  assert.throws(() => compilePolicy('---\nspec: ai-governance/v0.1\nsystem: { name: "x" }\n---\n', 'rego'), /no agent section/);
  assert.throws(() => compilePolicy(POLICY_TEST_RULES, 'yaml'), /Unknown target/);
});

test('sqlFacts finds writes and tables', () => {
  assert.deepEqual(sqlFacts('SELECT count(*) FROM orders'), { sql_writes: false, sql_tables: ['orders'] });
  assert.equal(sqlFacts('DELETE FROM orders WHERE id = 1').sql_writes, true);
  assert.deepEqual(sqlFacts('SELECT p.name FROM products p JOIN orders o ON o.pid = p.id').sql_tables, ['products', 'orders']);
});

test('agentModel reads the new agent fields', () => {
  const m = agentModel(parseGovernanceMd(POLICY_TEST_RULES).frontMatter);
  assert.equal(m.breaker, 3);
  assert.deepEqual(m.memory, ['user']);
  assert.equal(m.tools.find(t => t.name === 'reset_password').run_as, 'svc-helpdesk');
  assert.deepEqual(m.untrusted, ['email', 'web']);
});

function haveOpa() {
  try { execFileSync(process.env.OPA || 'opa', ['version'], { stdio: 'ignore' }); return true; } catch { return false; }
}

test('rails, OPA and Cedar give the same decision on 600 requests', async t => {
  if (!haveOpa()) return t.skip('opa binary not found (set OPA=/path/to/opa); CI job "policy-engines" runs this');
  try { await loadCedar(); } catch { return t.skip('@cedar-policy/cedar-wasm not installed; CI job "policy-engines" runs this'); }
  const r = await runEquivalence({ n: 600, log: () => {} });
  assert.equal(r.cases, 600);
  assert.ok(r.allows > 50 && r.allows < 550, `a useful mix of allowed and blocked requests (allowed ${r.allows})`);
  assert.deepEqual(r.diffs, []);
});
